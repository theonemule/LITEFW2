# shellcheck shell=sh
# Layer 2 / layer 3 interface management. Kernel first, then persisted.

# ---------------------------------------------------------------- live reads
iface_exists() { [ -e "/sys/class/net/$1" ]; }
iface_master() {
  [ -e "/sys/class/net/$1/master" ] || return 0
  basename "$(readlink "/sys/class/net/$1/master")"
}
iface_mac() { cat "/sys/class/net/$1/address"; }
iface_ips() { ip -4 -o addr show dev "$1" scope global 2>/dev/null | awk '{print $4}'; }
iface_members() {
  local _m
  for _m in /sys/class/net/"$1"/brif/*; do [ -e "$_m" ] && basename "$_m"; done; return 0
}
iface_kind() {
  local _k
  if [ "$1" = lo ]; then echo loopback; return; fi
  _k=$(ip -d -j link show dev "$1" 2>/dev/null | jq -r '.[0] | (.linkinfo.info_kind // "") + "|" + (.link_type // "")')
  case "$_k" in
    bridge\|*) echo bridge;;
    vlan\|*) echo vlan;;
    \|ether|veth\|ether) echo physical;;
    *) echo other;;
  esac
}
# vlan children of an interface
iface_vlan_children() {
  ip -d -j link show 2>/dev/null | jq -r --arg p "$1" '.[] | select((.linkinfo.info_kind // "")=="vlan" and (.link // "")==$p) | .ifname'
}
meta_get() { # IFACE KEY
  local _a
  _a=$(cat "/sys/class/net/$1/ifalias" 2>/dev/null || true)
  case "$_a" in lfw:*) :;; *) return 0;; esac
  printf '%s' "${_a#lfw:}" | tr ';' '\n' | sed -n "s/^$2=//p" | head -n 1
}
role_of() { local _r; _r=$(meta_get "$1" role); printf '%s' "${_r:-none}"; }
set_meta() { # IFACE ROLE LABEL
  if [ "${2:-none}" = none ] && [ -z "${3:-}" ]; then
    try ip link set dev "$1" alias ""
  else
    run ip link set dev "$1" alias "lfw:role=${2:-none};name=${3:-}"
  fi
}
ifaces_with_role() {
  local _p _i
  for _p in /sys/class/net/*; do
    _i=${_p##*/}; [ "$(role_of "$_i")" = "$1" ] && echo "$_i"
  done; return 0
}
wan_iface() { ifaces_with_role wan | head -n 1; }
lan_ifaces() { ifaces_with_role lan; }

net_inventory() {
  local _links _addrs _routes _vl _dh
  _links=$(ip -d -j link show)
  _addrs=$(ip -4 -j addr show)
  _routes=$(ip -4 -j route show table main)
  _vl=$(bridge -j vlan show 2>/dev/null); [ -n "$_vl" ] || _vl='[]'
  _dh=$(dhcp_ifaces | jq -R . | jq -s .)
  jq -n --argjson L "$_links" --argjson A "$_addrs" --argjson R "$_routes" \
        --argjson V "$_vl" --argjson D "$_dh" -f "$LFW_LIB/inventory.jq"
}

# Serialise the live topology to /etc/network/interfaces (boot persistence).
net_persist() {
  local _inv _t
  _inv=$(net_inventory)
  _t=$(mktemp)
  {
    echo '# Generated by LiteFWM from the running system. LiteFWM applies changes to the'
    echo '# kernel immediately and rewrites this file afterwards so they survive reboot.'
    echo
    echo 'auto lo'
    echo 'iface lo inet loopback'
    echo
    printf '%s' "$_inv" | jq -r --argjson I "$_inv" -n -f "$LFW_LIB/persist.jq"
  } >"$_t" || die "failed to render network configuration"
  mkdir -p "$(dirname "$LFW_IFACES")"
  install -m 0644 "$_t" "$LFW_IFACES"
  rm -f "$_t"
}

# ---------------------------------------------------------------- DHCP client
dhcp_pid() {
  local _f _p
  _f=/var/run/udhcpc.$1.pid
  [ -r "$_f" ] || return 1
  _p=$(cat "$_f" 2>/dev/null)
  [ -n "$_p" ] && kill -0 "$_p" 2>/dev/null && printf '%s' "$_p"
}
dhcp_running() { dhcp_pid "$1" >/dev/null; }
dhcp_ifaces() {
  local _f _i
  for _f in /var/run/udhcpc.*.pid; do
    [ -e "$_f" ] || continue
    _i=${_f#/var/run/udhcpc.}; _i=${_i%.pid}
    dhcp_running "$_i" && echo "$_i"
  done; return 0
}
# dhcp_stop IFACE [kill]: kill = SIGKILL, keeps the address and sends no RELEASE.
dhcp_stop() {
  local _p _n
  _p=$(dhcp_pid "$1" || true)
  if [ -n "$_p" ]; then
    if [ "${2:-}" = kill ]; then kill -KILL "$_p" 2>/dev/null; else kill "$_p" 2>/dev/null; fi
    _n=0; while kill -0 "$_p" 2>/dev/null && [ $_n -lt 30 ]; do sleep 0.1; _n=$((_n+1)); done
  fi
  rm -f "/var/run/udhcpc.$1.pid"
}
# dhcp_start IFACE [REQUEST_IP] [keep]: keep = skip the initial address flush so
# an address copied onto IFACE stays reachable while the lease is renewed.
dhcp_start() {
  dhcp_stop "$1" kill
  mkdir -p "$LFW_RUN"
  if [ "${3:-}" = keep ]; then : >"$LFW_RUN/keep.$1"; else rm -f "$LFW_RUN/keep.$1"; fi
  set -- "$1" "${2:-}"
  if [ -n "$2" ]; then
    udhcpc -b -R -p "/var/run/udhcpc.$1.pid" -i "$1" -s "$LFW_UDHCPC_SCRIPT" -r "$2" >/dev/null 2>&1 </dev/null 9>&-
  else
    udhcpc -b -R -p "/var/run/udhcpc.$1.pid" -i "$1" -s "$LFW_UDHCPC_SCRIPT" >/dev/null 2>&1 </dev/null 9>&-
  fi
  dhcp_running "$1" || die "could not start DHCP client on $1"
}

# ---------------------------------------------------------------- L3 moves
# has_l3 IFACE: any address, DHCP client, role/label or DHCP server.
has_l3() {
  [ -n "$(iface_ips "$1")" ] || dhcp_running "$1" || [ -n "$(meta_get "$1" role)$(meta_get "$1" name)" ] || dhcpd_exists "$1"
}

# l3_move FROM TO [CMD...]
# Moves the complete L3 identity (addresses, routes, DHCP client, role/label,
# DHCP server, firewall references) from FROM to TO. CMD runs after the
# addresses exist on TO and before they are removed from FROM (the L2 change).
l3_move() {
  local _from _to _ips _dhcp _routes _role _label _c _tab _dst _gw _met _req
  _from=$1 _to=$2; shift 2
  _ips=$(iface_ips "$_from")
  _dhcp=false; dhcp_running "$_from" && _dhcp=true
  _routes=$(ip -4 -j route show dev "$_from" | jq -r '.[] | select((.protocol // "")!="kernel") | [.dst, (.gateway // "-"), ((.metric // 0)|tostring)] | @tsv')
  _role=$(meta_get "$_from" role); _label=$(meta_get "$_from" name)

  [ "$_dhcp" = false ] || dhcp_stop "$_from" kill
  for _c in $_ips; do try ip addr add "$_c" dev "$_to"; done
  run ip link set dev "$_to" up
  [ $# -eq 0 ] || "$@"
  _tab=$(printf '\t')
  printf '%s\n' "$_routes" | while IFS=$_tab read -r _dst _gw _met; do
    [ -n "$_dst" ] || continue
    if [ "$_gw" = - ]; then
      try ip route replace "$_dst" dev "$_to" metric "$_met"
    else
      try ip route replace "$_dst" via "$_gw" dev "$_to" metric "$_met"
    fi
    try ip route del "$_dst" dev "$_from" metric "$_met"
  done
  try ip -4 addr flush dev "$_from" scope global
  set_meta "$_to" "${_role:-none}" "$_label"
  set_meta "$_from" none ""
  if [ "$_dhcp" = true ]; then
    _req=$(printf '%s\n' "$_ips" | head -n 1); _req=${_req%/*}
    dhcp_start "$_to" "$_req" keep
  fi
  dhcpd_rename "$_from" "$_to"
  dns_listen_sync; dnsmasq_apply
  fw_rename_iface "$_from" "$_to"
}

# ---------------------------------------------------------------- interface ops
need_iface() { is_ifname "$1" || die "invalid interface name: $1"; iface_exists "$1" || die "interface $1 does not exist"; }

op_iface_set() {
  _i=$(jget name); need_iface "$_i"
  _mtu=$(jget mtu)
  if [ -n "$_mtu" ]; then
    is_uint "$_mtu" && [ "$_mtu" -ge 576 ] && [ "$_mtu" -le 9216 ] || die "MTU must be 576-9216"
    run ip link set dev "$_i" mtu "$_mtu"
  fi
  net_persist
}

# Enslave PORT to BRIDGE and, for VLAN-aware bridges, trunk the bridge's VLAN
# sub-interfaces onto the new port.
bridge_enslave() {
  local _c _vid
  run ip link set dev "$1" master "$2"
  run ip link set dev "$1" up
  if [ "$(ip -d -j link show dev "$2" | jq -r '.[0].linkinfo.info_data.vlan_filtering // 0')" = 1 ]; then
    for _c in $(iface_vlan_children "$2"); do
      _vid=$(ip -d -j link show dev "$_c" | jq -r '.[0].linkinfo.info_data.id')
      try bridge vlan add dev "$1" vid "$_vid"
    done
  fi
}

bridge_add_member() { # BRIDGE PORT
  local _b _p _cur
  _b=$1 _p=$2
  need_iface "$_p"
  [ "$_p" != "$_b" ] || die "a bridge cannot be a member of itself"
  case "$(iface_kind "$_p")" in physical|vlan) :;; *) die "$_p cannot be a bridge member (only Ethernet and VLAN interfaces)";; esac
  _cur=$(iface_master "$_p")
  [ "$_cur" != "$_b" ] || return 0
  [ -z "$_cur" ] || die "$_p is already a member of $_cur"
  [ -z "$(iface_vlan_children "$_b" | grep -Fx "$_p")" ] || die "$_p is a VLAN of $_b"
  if has_l3 "$_p"; then
    if [ -n "$(iface_ips "$_b")" ] || dhcp_running "$_b"; then
      die "$_p and $_b both have IP configuration; clear one of them first"
    fi
    # The bridge takes over the port's MAC so upstream DHCP/ARP see the same host.
    [ -n "$(iface_members "$_b")" ] || run ip link set dev "$_b" address "$(iface_mac "$_p")"
    l3_move "$_p" "$_b" bridge_enslave "$_p" "$_b"
  else
    [ -n "$(iface_members "$_b")" ] || [ -n "$(iface_ips "$_b")" ] || run ip link set dev "$_b" address "$(iface_mac "$_p")"
    bridge_enslave "$_p" "$_b"
  fi
}

op_bridge_create() {
  _b=$(jget name)
  is_ifname "$_b" || die "invalid bridge name"
  ! iface_exists "$_b" || die "interface $_b already exists"
  for _m in $(jlist members); do need_iface "$_m"; done
  run ip link add name "$_b" type bridge
  if jbool vlanFiltering; then run ip link set dev "$_b" type bridge vlan_filtering 1; fi
  run ip link set dev "$_b" up
  for _m in $(jlist members); do bridge_add_member "$_b" "$_m"; done
  net_persist
  log_op "bridge.create $_b members=$(jlist members | tr '\n' ' ')"
}

need_bridge() { need_iface "$1"; [ "$(iface_kind "$1")" = bridge ] || die "$1 is not a bridge"; }

op_bridge_set() {
  _b=$(jget name); need_bridge "$_b"
  if jhas vlanFiltering; then
    if jbool vlanFiltering; then _v=1; else _v=0; fi
    run ip link set dev "$_b" type bridge vlan_filtering "$_v"
    if [ "$_v" = 1 ]; then
      for _c in $(iface_vlan_children "$_b"); do
        _vid=$(ip -d -j link show dev "$_c" | jq -r '.[0].linkinfo.info_data.id')
        try bridge vlan add dev "$_b" vid "$_vid" self
        for _m in $(iface_members "$_b"); do try bridge vlan add dev "$_m" vid "$_vid"; done
      done
    fi
  fi
  net_persist
  log_op "bridge.set $_b vlanFiltering=${_v:-}"
}

op_bridge_addmember() {
  _b=$(jget bridge); need_bridge "$_b"
  bridge_add_member "$_b" "$(jget member)"
  net_persist
  log_op "bridge.addmember $_b $(jget member)"
}

op_bridge_delmember() {
  _b=$(jget bridge); _p=$(jget member); need_bridge "$_b"; need_iface "$_p"
  [ "$(iface_master "$_p")" = "$_b" ] || die "$_p is not a member of $_b"
  run ip link set dev "$_p" nomaster
  net_persist
  log_op "bridge.delmember $_b $_p"
}

op_bridge_delete() {
  _b=$(jget name); need_bridge "$_b"
  _kids=$(iface_vlan_children "$_b" | tr '\n' ' ')
  [ -z "$_kids" ] || die "delete the VLAN interfaces on $_b first: $_kids"
  _members=$(iface_members "$_b")
  if has_l3 "$_b"; then
    _target=""
    for _m in $_members; do [ "$(iface_kind "$_m")" = physical ] && { _target=$_m; break; }; done
    [ -n "$_target" ] || _target=$(printf '%s\n' "$_members" | head -n 1)
    if [ -n "$_target" ]; then
      # Hand the bridge's IP identity back to its port so the host stays reachable.
      l3_move "$_b" "$_target" run ip link set dev "$_target" nomaster
    else
      fw_refs "$_b" && die "firewall rules reference $_b; remove them first"
      dhcp_stop "$_b"
      dhcpd_remove "$_b"
    fi
  fi
  for _m in $(iface_members "$_b"); do try ip link set dev "$_m" nomaster; done
  run ip link del dev "$_b"
  dns_listen_sync; dnsmasq_apply; fw_sync
  net_persist
  log_op "bridge.delete $_b"
}

valid_vid() { is_uint "$1" && [ "$1" -ge 1 ] && [ "$1" -le 4094 ]; }

# bridge.portvlans {bridge, port, pvid, tagged:[...]}: port may be the bridge itself.
op_bridge_portvlans() {
  _b=$(jget bridge); _p=$(jget port); need_bridge "$_b"; need_iface "$_p"
  _self=""
  if [ "$_p" = "$_b" ]; then _self=self; else [ "$(iface_master "$_p")" = "$_b" ] || die "$_p is not a member of $_b"; fi
  _pvid=$(jget pvid)
  [ -z "$_pvid" ] || [ "$_pvid" = 0 ] || valid_vid "$_pvid" || die "invalid PVID"
  for _v in $(jlist tagged); do valid_vid "$_v" || die "invalid VLAN id $_v"; done
  for _v in $(bridge -j vlan show dev "$_p" | jq -r --arg p "$_p" '.[] | select(.ifname==$p) | .vlans[] | range(.vlan; (.vlanEnd // .vlan) + 1)'); do
    try bridge vlan del dev "$_p" vid "$_v" $_self
  done
  if [ -n "$_pvid" ] && [ "$_pvid" != 0 ]; then run bridge vlan add dev "$_p" vid "$_pvid" pvid untagged $_self; fi
  for _v in $(jlist tagged); do
    [ "$_v" = "$_pvid" ] && continue
    run bridge vlan add dev "$_p" vid "$_v" $_self
  done
  net_persist
  log_op "bridge.portvlans $_b $_p pvid=$_pvid tagged=$(jlist tagged | tr '\n' ',')"
}

op_vlan_create() {
  _parent=$(jget parent); _vid=$(jget vid); _n=$(jget name)
  need_iface "$_parent"
  valid_vid "$_vid" || die "VLAN id must be 1-4094"
  _pk=$(iface_kind "$_parent")
  case "$_pk" in physical|bridge) :;; *) die "VLANs can be created on Ethernet interfaces or bridges";; esac
  [ -n "$_n" ] || _n="$_parent.$_vid"
  is_ifname "$_n" || die "invalid VLAN interface name '$_n' (max 15 characters)"
  ! iface_exists "$_n" || die "interface $_n already exists"
  run ip link add link "$_parent" name "$_n" type vlan id "$_vid"
  run ip link set dev "$_n" up
  if [ "$_pk" = bridge ] && [ "$(ip -d -j link show dev "$_parent" | jq -r '.[0].linkinfo.info_data.vlan_filtering // 0')" = 1 ]; then
    run bridge vlan add dev "$_parent" vid "$_vid" self
    for _m in $(iface_members "$_parent"); do try bridge vlan add dev "$_m" vid "$_vid"; done
  fi
  net_persist
  log_op "vlan.create $_n parent=$_parent vid=$_vid"
}

op_vlan_delete() {
  _n=$(jget name); need_iface "$_n"
  [ "$(iface_kind "$_n")" = vlan ] || die "$_n is not a VLAN interface"
  fw_refs "$_n" && die "firewall rules or port forwards reference $_n; remove them first"
  _m=$(iface_master "$_n"); [ -z "$_m" ] || die "$_n is a member of bridge $_m; remove it from the bridge first"
  _parent=$(ip -d -j link show dev "$_n" | jq -r '.[0].link')
  _vid=$(ip -d -j link show dev "$_n" | jq -r '.[0].linkinfo.info_data.id')
  dhcp_stop "$_n"
  dhcpd_remove "$_n"
  run ip link del dev "$_n"
  if [ "$(iface_kind "$_parent")" = bridge ]; then try bridge vlan del dev "$_parent" vid "$_vid" self; fi
  dns_listen_sync; dnsmasq_apply; fw_sync
  net_persist
  log_op "vlan.delete $_n"
}

# ---------------------------------------------------------------- segments (L3)
write_resolv() {
  local _t _d
  _t=$(mktemp)
  for _d in "$@"; do echo "nameserver $_d"; done >"$_t"
  chmod 0644 "$_t"
  cat "$_t" >/etc/resolv.conf 2>/dev/null || die "cannot write /etc/resolv.conf"
  rm -f "$_t"
}

del_default_routes() { # IFACE
  while ip -4 route show default dev "$1" 2>/dev/null | grep -q .; do
    ip -4 route del default dev "$1" 2>/dev/null || break
  done
}

# segment.set {interface, label, role: wan|lan|none, mode: dhcp|static|none,
#              addresses: [cidr...], gateway, dns: [ip...]}
op_segment_set() {
  _i=$(jget interface); need_iface "$_i"
  case "$(iface_kind "$_i")" in physical|bridge|vlan) :;; *) die "$_i cannot carry a network segment";; esac
  _mst=$(iface_master "$_i"); [ -z "$_mst" ] || die "$_i is a member of bridge $_mst; configure $_mst instead"
  _role=$(jget role); _role=${_role:-none}
  case "$_role" in wan|lan|none) :;; *) die "role must be wan, lan or none";; esac
  _label=$(jget label)
  [ -z "$_label" ] || is_label "$_label" || die "invalid segment name (letters, digits, space, _ . -; max 32)"
  _mode=$(jget mode); _mode=${_mode:-static}
  case "$_mode" in dhcp|static|none) :;; *) die "mode must be dhcp, static or none";; esac
  _addrs=$(jlist addresses)
  _gw=$(jget gateway)
  if [ "$_role" = wan ]; then
    _w=$(wan_iface); [ -z "$_w" ] || [ "$_w" = "$_i" ] || die "$_w is already the WAN segment"
  fi
  if [ "$_mode" = static ]; then
    [ -n "$_addrs" ] || die "a static segment needs at least one address"
    for _a in $_addrs; do is_cidr "$_a" || die "invalid address $_a (use a.b.c.d/nn)"; done
    if [ -n "$_gw" ]; then
      is_ipv4 "$_gw" || die "invalid gateway"
      [ "$_role" = wan ] || die "only the WAN segment has a gateway"
      _ok=false; for _a in $_addrs; do in_cidr "$_gw" "$_a" && _ok=true; done
      [ "$_ok" = true ] || die "gateway $_gw is not inside any address of $_i"
    fi
  else
    _gw=""
  fi
  for _d in $(jlist dns); do is_ipv4 "$_d" || die "invalid DNS server $_d"; done

  case "$_mode" in
    dhcp)
      if ! dhcp_running "$_i"; then
        try ip -4 addr flush dev "$_i" scope global
        dhcp_start "$_i"
      fi;;
    static)
      if dhcp_running "$_i"; then dhcp_stop "$_i" kill; fi
      for _c in $(iface_ips "$_i"); do
        printf '%s\n' "$_addrs" | grep -Fxq "$_c" || run ip addr del "$_c" dev "$_i"
      done
      for _c in $_addrs; do
        iface_ips "$_i" | grep -Fxq "$_c" || run ip addr add "$_c" dev "$_i"
      done
      run ip link set dev "$_i" up
      del_default_routes "$_i"
      if [ -n "$_gw" ]; then
        _o=$(ip -4 route show default | awk '{for(i=1;i<=NF;i++) if($i=="dev") print $(i+1)}' | head -n 1)
        [ -z "$_o" ] || [ "$_o" = "$_i" ] || del_default_routes "$_o"
        run ip route replace default via "$_gw" dev "$_i"
      fi
      if [ "$_role" = wan ] && [ -n "$(jlist dns)" ]; then
        # shellcheck disable=SC2046
        write_resolv $(jlist dns)
      fi;;
    none)
      dhcp_stop "$_i" kill
      try ip -4 addr flush dev "$_i" scope global
      del_default_routes "$_i";;
  esac
  set_meta "$_i" "$_role" "$_label"

  if dhcpd_exists "$_i"; then
    if [ "$_role" != lan ] || [ "$_mode" != static ]; then
      dhcpd_remove "$_i"; warn "DHCP server on $_i was removed (it needs a static LAN segment)"
    elif ! dhcpd_fits "$_i"; then
      dhcpd_remove "$_i"; warn "DHCP server on $_i was removed because its range is outside the new addresses"
    fi
  fi
  dns_listen_sync; dnsmasq_apply; fw_sync
  net_persist
  log_op "segment.set $_i role=$_role mode=$_mode addrs=$(printf '%s' "$_addrs" | tr '\n' ' ')gw=$_gw"
}
